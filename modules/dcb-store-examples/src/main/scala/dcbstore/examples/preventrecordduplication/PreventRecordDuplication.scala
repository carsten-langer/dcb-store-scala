package dcbstore.examples.preventrecordduplication

import dcbstore.decisionmodel.*
import dcbstore.decisionmodel.SingleProjection.handler
import dcbstore.examples.{*, given}
import dcbstore.{DcbStore, Event, Tags}

import scala.concurrent.{ExecutionContext, Future}

// The example https://dcb.events/examples/prevent-record-duplication/: an order is placed only once, even if the
// request is repeated, e.g. retried by a client after a timeout.
// With DCB, the client generates a random idempotency token and includes it in the command. The OrderPlaced event is
// tagged with it, besides the server-generated order id, so a decision model on the token's tag detects its reuse,
// without exposing domain identifiers to the client or storing tokens elsewhere.

type OrderId = String
type IdempotencyToken = String

def orderTags(orderId: OrderId): Tags = Tags("order", orderId)

def idempotencyTokenTags(idempotencyToken: IdempotencyToken): Tags = Tags("idempotencyToken", idempotencyToken)


////////////////////////////////////////
// Events
////////////////////////////////////////

final case class OrderPlaced(orderId: OrderId, idempotencyToken: IdempotencyToken) derives CanEqual:
  def toEvent: Event[EventType, OrderPlaced] =
    event(this, Tags(orderTags(orderId), idempotencyTokenTags(idempotencyToken)))


////////////////////////////////////////
// Projections
////////////////////////////////////////

def idempotencyTokenWasUsed(idempotencyToken: IdempotencyToken) = SingleProjection(
  internalState = false,
  handlers = Map(
    handler(handlerF = (_: Boolean, _: OrderPlaced) => true, tags = idempotencyTokenTags(idempotencyToken)),
  ),
)


////////////////////////////////////////
// Commands
////////////////////////////////////////

// The order id is generated by the server, the idempotency token by the client.
final case class PlaceOrder(orderId: OrderId, idempotencyToken: IdempotencyToken)

/**
 * Handles the command: builds a decision model from a named tuple of projections, checks the business rule on its
 * typed state, and appends the resulting event with the decision model's append condition. See [[appendIfAccepted]]
 * for the outcomes. The append condition covers the token, so of two concurrent requests with the same token only one
 * places the order.
 */
final class PreventRecordDuplicationCommandHandler(store: DcbStore[EventType, DataSuper])(using ExecutionContext):

  def handle(command: PlaceOrder): Future[Either[Rejected, Unit]] =
    import command.*
    store.buildDecisionModel((tokenUsed = idempotencyTokenWasUsed(idempotencyToken))).flatMap:
      (state, appendConditionO) =>
        val decision =
          if state.tokenUsed then Left(Rejected("Order was already placed"))
          else Right(List(OrderPlaced(orderId, idempotencyToken).toEvent))
        appendIfAccepted(store)(decision, appendConditionO)
